    public static Dhikr Random(Dhikr? not = null)
    {
        Dhikr d; int n = 0;
        do { d = All[R.Next(All.Length)]; } while (ReferenceEquals(d, not) && ++n < 10);
        return d;
    }
    /// <summary>A dhikr short enough for a Windows notification.</summary>
    public static Dhikr RandomShort()
    {
        var s = All.Where(x => x.Text.Length <= 200).ToArray();
        return s[R.Next(s.Length)];
    }
